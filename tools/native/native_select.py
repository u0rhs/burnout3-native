#!/usr/bin/env python3
"""native_select: the native backend's selection (boot1, docs/standalone.md §8): what build/gen_native generates.

The live table (config/game_overrides.txt -> gen/decomp, what the unit tests build) holds the functions proven one by
one. The native backend has no fallback, so it links every function that can be generated at all: the live
selection (kept first, with its options) plus every decomp function that candidates.py reports `ok` (generates and
compiles alone in both float modes). decomp2host then generates them together with --keep-going; a unit that fails
together is listed in build/gen_native/failed.tsv. Correctness is not assumed: native_check / native_boot compare
with retail.

  native_select.py --live config/game_overrides.txt --candidates CAND.tsv [--exclude FILE] --out FILE
  native_select.py --base config/native_select.txt --out build/native/select.txt   (+ every port-track marker)
CAND.tsv: `candidates.py --decomp SNAP --calls --compile` output. --exclude: addresses (first word per line) to
leave out, with the reason as a comment (functions that break a combined generation).
"""
import argparse
import os
import re


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--live", default="")
    ap.add_argument("--candidates", default="")
    ap.add_argument("--base", default="", help="build mode: copy this selection, then append every port-track function (decomp2host PORT_TRACKS)")
    ap.add_argument("--exclude", default="")
    ap.add_argument("--sinit-retail", action="store_true",
                    help="gen1 (option A): leave the static initialisers (0x4D3E00-0x4DD81C) and their walker "
                         "func_00100240 out, so they run retail in the fallback mini at boot and their 16-byte constants' "
                         "stale stack lanes come out as retail's")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.base:   # the build's full selection: the committed one + every port-track marker (make: build/native/select.txt)
        import glob
        import sys
        sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "decomp2host"))
        from decomp2host import PORT_ROOT, PORT_TRACKS   # the one list of port tracks (rw, rwa, ...)
        lines = open(a.base).read().splitlines()
        if a.sinit_retail:
            def _sinit(l):
                w = l.split()[0] if l.split() else ""
                return re.fullmatch(r"[0-9A-Fa-f]{8}", w) and (0x004D3E00 <= int(w, 16) < 0x004DD820 or int(w, 16) == 0x00100240)
            dropped = [l for l in lines if _sinit(l)]
            lines = [l for l in lines if not _sinit(l)]
            print("native_select: --sinit-retail: %d static initialisers / their walker left to the fallback" % len(dropped))
        have = {int(l.split()[0], 16) for l in lines if l[:1] not in ("#", "") and re.fullmatch(r"[0-9A-Fa-f]{8}", l.split()[0])}
        n = {}
        with open(a.out, "w") as f:
            f.write("\n".join(lines) + "\n")
            for track, d in sorted(PORT_TRACKS.items()):
                for g in sorted(glob.glob(os.path.join(PORT_ROOT, d, "*.cpp"))):
                    for mm in re.finditer(r"^//\s*0x([0-9A-Fa-f]{8})[ \t]*$", open(g, errors="replace").read(), re.M):
                        addr = int(mm.group(1), 16)
                        if addr not in have:
                            have.add(addr)
                            n[track] = n.get(track, 0) + 1
                            f.write("%08X %s   # %s\n" % (addr, track, os.path.relpath(g, PORT_ROOT)))
        print("native_select: %s + %s -> %s" % (a.base, ", ".join("%d %s" % (v, k) for k, v in sorted(n.items())) or "no port functions", a.out))
        return
    excl = set()
    if a.exclude:
        for line in open(a.exclude):
            p = line.split("#")[0].split()
            if p:
                excl.add(int(p[0], 16))
    rows, seen = [], set()
    for line in open(a.live):
        p = line.split("#")[0].split()
        if p and re.fullmatch(r"[0-9A-Fa-f]{8}", p[0]):
            addr = int(p[0], 16)
            if addr in seen or addr in excl:
                continue
            seen.add(addr)
            rows.append(" ".join(p))
    n_live = len(rows)
    extra = []
    for line in open(a.candidates):
        p = line.rstrip("\n").split("\t")
        if len(p) < 7 or not re.fullmatch(r"[0-9A-F]{8}", p[0]) or p[6] != "ok":
            continue
        addr = int(p[0], 16)
        if addr in seen or addr in excl:
            continue
        seen.add(addr)
        extra.append((addr, p[1], p[2]))
    rw = []
    with open(a.out, "w") as f:
        f.write("# The native backend's selection (generated by tools/native/native_select.py; do not edit by hand).\n")
        f.write("# %d from the live selection (config/game_overrides.txt), %d more that generate and compile alone\n"
                % (n_live, len(extra)))
        f.write("# (tools/decomp2host/candidates.py ok), %d excluded. <address> <track> [options]\n" % len(excl))
        for r in rows:
            f.write(r + "\n")
        for addr, track, name in sorted(extra):
            f.write("%08X %s   # %s\n" % (addr, track, name))
        for addr, src in sorted(rw):
            f.write("%08X rw   # %s (RenderWare 3.6 as C in the port)\n" % (addr, src))
    print("native_select: %d live + %d more + %d rw -> %s" % (n_live, len(extra), len(rw), a.out))


if __name__ == "__main__":
    main()
