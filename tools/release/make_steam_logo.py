#!/usr/bin/env python3
"""make_steam_logo.py [--check]: builds include/b3port/steam_logo_data.h from docs/logo.png -- the port's logo, built
into the launcher for Settings > Launcher > ADD TO STEAM (src/b3launcher/steam_art.h draws the cover, wide capsule and
background around it and writes the logo itself as Steam's logo file).

  python3 -I tools/release/make_steam_logo.py            write the header
  python3 -I tools/release/make_steam_logo.py --check    exit 1 if the header differs from what docs/logo.png makes

The PNG file's bytes are kept as they are (a string literal: printable characters as themselves, the rest as
three-digit octal escapes).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "docs", "logo.png")
OUT = os.path.join(ROOT, "include", "b3port", "steam_logo_data.h")


def literal_lines(data, per_line=96):
    out = []
    for at in range(0, len(data), per_line):
        s = []
        for b in data[at:at + per_line]:
            c = chr(b)
            if 0x20 <= b < 0x7F and c not in '"\\?':
                s.append(c)
            else:
                s.append("\\%03o" % b)
        out.append('    "' + "".join(s) + '"')
    return out


def header():
    data = open(SRC, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("make_steam_logo: %s is not a PNG" % SRC)
    lines = [
        "// generated by tools/release/make_steam_logo.py from docs/logo.png; do not edit by hand.",
        "// The port's logo as a PNG file's bytes, for ADD TO STEAM's pictures (src/b3launcher/steam_art.cpp).",
        "#pragma once",
        "#include <cstddef>",
        "namespace b3port {",
        "inline constexpr std::size_t kSteamLogoPngSize = %d;" % len(data),
        "inline constexpr unsigned char kSteamLogoPng[kSteamLogoPngSize + 1] =",
    ]
    lines += literal_lines(data)
    lines[-1] += ";"
    lines.append("}  // namespace b3port")
    return "\n".join(lines) + "\n"


def main():
    want = header()
    if "--check" in sys.argv[1:]:
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != want:
            print("make_steam_logo: %s differs from docs/logo.png (run tools/release/make_steam_logo.py)" % OUT)
            return 1
        print("make_steam_logo: %s matches docs/logo.png" % os.path.relpath(OUT, ROOT))
        return 0
    with open(OUT, "w", newline="\n") as f:
        f.write(want)
    print("make_steam_logo: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
