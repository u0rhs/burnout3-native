#!/bin/bash
# version_info.sh -- the build's version source (include/b3report/version.h's version() / build_date()):
#   tools/release/version_info.sh <out.cpp>     writes it; rewritten only when its text changes (a new commit or day)
#   tools/release/version_info.sh --print       the version string alone (packaging: the zip's name)
# The base is the repo's VERSION file; the commit is git's short hash, "-dirty" when tracked files (outside gen/)
# differ from it (B3_VERSION_HASH=... overrides it: a build from an exported tree); the date is today's (UTC).
set -euo pipefail
PORT=$(cd "$(dirname "$0")/../.." && pwd)
BASE=$(tr -d ' \r\n' < "$PORT/VERSION" 2>/dev/null || true)
[ -n "$BASE" ] || BASE=0.0.0
if [ -n "${B3_VERSION_HASH+x}" ]; then HASH=$B3_VERSION_HASH
else
    HASH=$(git -C "$PORT" rev-parse --short=8 HEAD 2>/dev/null || true)
    if [ -n "$HASH" ] && ! git -C "$PORT" diff --quiet HEAD -- . ':(exclude)gen' 2>/dev/null; then HASH=$HASH-dirty; fi
fi
VER=$BASE${HASH:++$HASH}
DATE=$(date -u +%Y-%m-%d)
if [ "${1:-}" = --print ]; then echo "$VER"; exit 0; fi
OUT=${1:?usage: version_info.sh <out.cpp> | --print}
TEXT="// GENERATED by tools/release/version_info.sh (include/b3report/version.h); not committed
#include \"b3report/version.h\"
namespace b3port {
const char* version() { return \"$VER\"; }
const char* build_date() { return \"$DATE\"; }
}  // namespace b3port"
mkdir -p "$(dirname "$OUT")"
if [ ! -f "$OUT" ] || [ "$(cat "$OUT")" != "$TEXT" ]; then printf '%s\n' "$TEXT" > "$OUT"; fi
