#!/usr/bin/env python3
"""Writes a C++ header embedding compiled shaders: <name>_spv (uint8 SPIR-V) and <name>_msl (MSL source) per shader,
with each GLSL source's SHA-256 in a "// source sha256 <name> <hex>" line (the header's link to its sources): every .vert,
.frag and .glsl file of the source dir (an embedded variant such as mesh_shadow.frag, built from mesh.frag with a define,
and an included .glsl are covered through the files they come from).
Usage: embed_shaders.py <dir with <s>.spv and <s>.metal> <out.h> <source dir> <shader>...   (called by build_shaders.sh)
       embed_shaders.py --check <header.h> <source dir>   (make test: every .vert / .frag / .glsl in the source dir has the
       SHA-256 the header was made from; needs no shader tools)"""
import hashlib
import os
import re
import sys

REBUILD = "run tools/render/build_shaders.sh (it rewrites src/b3gfx/shaders_gen.h) and commit the header with the shader"


def ident(name):
    return name.replace(".", "_")


def sha256_of(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def sources(src_dir):
    return sorted(n for n in os.listdir(src_dir) if n.endswith((".vert", ".frag", ".glsl")))


def check(header, src_dir):
    recorded = {}
    with open(header, "r") as f:
        for line in f:
            m = re.match(r"// source sha256 (\S+) ([0-9a-f]{64})$", line.rstrip("\n"))
            if m:
                recorded[m.group(1)] = m.group(2)
    bad = []
    if not recorded:
        bad.append("%s has no source SHA-256 lines" % header)
    for n in sources(src_dir):
        if n not in recorded:
            bad.append("%s is not in %s" % (n, header))
        elif sha256_of(os.path.join(src_dir, n)) != recorded[n]:
            bad.append("%s changed since %s was made" % (n, header))
    for n in sorted(set(recorded) - set(sources(src_dir))):
        bad.append("%s is in %s but not in %s" % (n, header, src_dir))
    for b in bad:
        print("embed_shaders: FAIL %s: %s" % (b, REBUILD))
    if not bad:
        print("embed_shaders: PASS %d shader sources match %s" % (len(recorded), header))
    return 1 if bad else 0


def main(argv):
    if len(argv) == 4 and argv[1] == "--check":
        return check(argv[2], argv[3])
    if len(argv) < 5:
        print(__doc__)
        return 2
    built, out, src_dir, names = argv[1], argv[2], argv[3], argv[4:]
    lines = ["// Generated by tools/render/build_shaders.sh from src/b3gfx/shaders; do not edit.",
             "// The sources it was made from (make test: embed_shaders.py --check):"]
    for n in sources(src_dir):
        lines.append("// source sha256 %s %s" % (n, sha256_of(os.path.join(src_dir, n))))
    lines += ["#pragma once", "#include <cstddef>", "#include <cstdint>", "namespace b3gfx::shaders {"]
    for n in names:
        spv = open(os.path.join(built, n + ".spv"), "rb").read()
        msl = open(os.path.join(built, n + ".metal"), "r").read()
        lines.append("alignas(4) inline const std::uint8_t %s_spv[] = {" % ident(n))
        for i in range(0, len(spv), 20):
            lines.append("    " + ", ".join("0x%02x" % b for b in spv[i:i + 20]) + ",")
        lines.append("};")
        lines.append("inline const char %s_msl[] = R\"MSL(%s)MSL\";" % (ident(n), msl))
    lines.append("}  // namespace b3gfx::shaders")
    open(out, "w").write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
